// Round 23: offline placement of the weathering decals. Loads the world base with the baked file ignored
// (?decals=plan), lets the page run planWeatheringDecals() once (surface rays, nine-point flat check, sliding
// of hand-placed posters), and writes src/weathering-decals.json. Runtime then builds the mesh from that file
// with zero rays. Re-run after the scene (buildings, props, station) or weathering.json decals change.
//   node scripts/bake-weathering-decals.cjs [time]       time = evening (default) | afternoon (query ?time=)
// Needs Playwright + a Chromium that can render WebGL (SwiftShader is fine; no frames are drawn here).
const path = require('node:path');
const fs = require('node:fs');
const { createStaticServer } = require('./baseline.cjs');
const { chromium } = require('playwright');
(async () => {
  const fix = path.resolve(__dirname, '..');
  const srv = createStaticServer(fix); await new Promise(r => srv.listen(8765, r));
  const b = await chromium.launch({ args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
  try {
    const p = await b.newPage({ viewport: { width: 640, height: 400 } });
    p.on('pageerror', e => console.log('PAGEERR', e.message.slice(0, 300)));
    await p.goto('http://localhost:8765/index.html?weathering=off&decals=plan');
    await p.waitForFunction(() => window.worldBase && window.worldBase.ready, null, { timeout: 1800000 });
    const out = await p.evaluate(() => {
      const d = window.worldBase.weatheringDecals;
      return { plan: { version: d.plan.version, fingerprint: d.plan.fingerprint, items: d.plan.items }, stats: d.stats, planStats: d.plan.stats, weatheringMs: window.worldBase.weatheringMs };
    });
    const file = path.join(fix, 'src', 'weathering-decals.json');
    fs.writeFileSync(file, JSON.stringify({ note: 'Generated by scripts/bake-weathering-decals.cjs. Positions are station-local.', ...out.plan }, null, 1) + '\n');
    console.log('wrote', file, 'items', out.plan.items.length, 'fingerprint', out.plan.fingerprint);
    console.log(JSON.stringify({ stats: out.stats, planStats: out.planStats, weatheringMs: out.weatheringMs }, null, 1));
  } finally { await b.close(); srv.close(); }
})().catch(e => { console.error(e); process.exit(1); });
